"""Run with `uv run scripts/optimize-assets.py` after changing source photos or fonts."""
import json
from pathlib import Path
from PIL import Image, ImageOps
from fontTools import subset

root = Path(__file__).resolve().parents[1]
photos = root / "public/images/community"
previews = photos / "previews"
previews.mkdir(exist_ok=True)
manifest = {}
for source in sorted(photos.glob("*.png")):
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original).convert("RGB")
        manifest[source.name] = []
        for width in sorted({min(size, image.width) for size in (480, 960, 1440)}):
            preview = image.copy()
            preview.thumbnail((width, 10000))
            preview.save(previews / f"{source.stem}-{width}.webp", quality=84, method=6)
            manifest[source.name].append({"src": f"community/previews/{source.stem}-{width}.webp", "width": preview.width})
with Image.open(root / "public/images/bop-logo.jpg") as image:
    logo = ImageOps.exif_transpose(image).convert("RGB")
    logo.thumbnail((256, 256))
    logo.save(root / "public/images/bop-logo.webp", quality=90, method=6)
options = subset.Options()
options.flavor = "woff2"
font = subset.load_font(str(root / "public/fonts/patrick-hand-regular.ttf"), options)
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=range(0x20, 0x100))
subsetter.subset(font)
subset.save_font(font, str(root / "public/fonts/patrick-hand-latin.woff2"), options)

(root / "src/data/photoPreviews.ts").write_text("// Generated by scripts/optimize-assets.py. Originals remain untouched.\nexport const photoPreviews: Record<string, { src: string; width: number }[]> = " + json.dumps(manifest, indent=2) + ";\n")
